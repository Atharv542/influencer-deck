
from __future__ import annotations

import csv
from pathlib import Path

from .enrichment import NOT_FOUND, is_valid_email

NA = "Not Available"


def _fmt_er(v):
    return f"{v:.2f}%" if isinstance(v, (int, float)) else NA


def _write(path: Path, rows: list[dict]) -> str:
    path.parent.mkdir(parents=True, exist_ok=True)
    cols = list(rows[0]) if rows else []
    with open(path, "w", newline="", encoding="utf-8-sig") as fh:
        w = csv.DictWriter(fh, fieldnames=cols)
        w.writeheader()
        w.writerows(rows)
    return str(path)


def dataset_rows(db) -> list[dict]:
    out = []
    for r in db.all("influencers", order="status ASC, followers DESC"):
        out.append({
            "Name": r["name"], "Platform": r["platform"],
            "Followers": r["followers"] if r["followers"] is not None else NA,
            "Engagement": _fmt_er(r.get("engagement_rate")),
            "Niche": r.get("primary_niche") or NA,
            "Email": r.get("email") or ("Not Evaluated (not shortlisted)" if r["status"] != "PASS" else NOT_FOUND),
            "Profile URL": r["profile_url"],
            "Content Theme": "; ".join(r.get("themes") or []) or NA,
            "Status": r["status"],
            "Pass/Fail Reason": "; ".join(r.get("fail_reasons") or []) or "; ".join(r.get("notes") or []) or "meets all criteria",
            "Country": r.get("country") or NA,
            "Discovered Via": r.get("discovered_via"),
        })
    return out


def enriched_rows(db) -> list[dict]:
    out = []
    for r in db.all("influencers", "status='PASS'", order="followers DESC"):
        out.append({
            "Influencer Name": r["name"], "Platform": r["platform"], "Profile URL": r["profile_url"],
            "Follower Count": r["followers"], "Engagement Rate": _fmt_er(r.get("engagement_rate")),
            "Category / Niche": r.get("primary_niche"), "Content Themes": "; ".join(r.get("themes") or []),
            "Contact Email": r.get("email") or NOT_FOUND, "Email Source": r.get("email_source"),
            "Instagram": r.get("instagram_url") or NA,
            "TikTok": r.get("tiktok_url") or NA, "Website": r.get("website") or NA,
            "Audience Age": r.get("audience_age"), "Audience Gender": r.get("audience_gender"),
            "Audience Geography": r.get("audience_geography"),
            "Engagement Videos Sampled": r.get("engagement_videos"),
        })
    return out


def message_rows(db) -> list[dict]:
    out = []
    for r in db.all("influencers", "status='PASS'", order="followers DESC"):
        m = db.get("messages", "channel_id", r["channel_id"])
        if not m:
            continue
        out.append({"Influencer": r["name"], "Email": r.get("email") or NOT_FOUND, "Subject": m["subject"],
                    "Email Pitch": m["email_body"], "Email Words": m["email_words"],
                    "Instagram DM": m["instagram_dm"], "DM Words": m["dm_words"],
                    "Collab Angle": m["angle"], "Generated By": m["source"], "Review Status": m["status"]})
    return out


def _flag(status):
    return {"sent": "Yes", "simulated": "Simulated", "test_sent": "Yes (test inbox)"}.get(status, "No")


def tracker_rows(db) -> list[dict]:
    out = []
    for r in db.all("influencers", "status='PASS'", order="followers DESC"):
        m = db.get("messages", "channel_id", r["channel_id"])
        em, dm = db.latest_log(r["channel_id"], "email"), db.latest_log(r["channel_id"], "instagram_dm")
        if em:
            status = em["status"] if em["status"] != "failed" else f"failed: {em['detail']}"
        elif not is_valid_email(r.get("email")):
            status = "Skipped - email Not Found (DM only)"
        elif not m:
            status = "Message not generated"
        elif m["status"] == "pending_review":
            status = "Awaiting review / approval"
        else:
            status = "Approved - pending send"
        out.append({
            "Influencer": r["name"], "Email": r.get("email") or NOT_FOUND,
            "Message Generated": "Yes" if m else "No",
            "Sent": _flag(em["status"]) if em else "No",
            "Date": em["ts"] if em else "", "Status": status,
            "Mode": em["mode"] if em else "",
            "Instagram DM": "Sent manually" if dm else ("In manual queue" if m else "No"),
        })
    return out


def dm_queue_rows(db) -> list[dict]:
    out = []
    for r in db.all("influencers", "status='PASS'", order="followers DESC"):
        m = db.get("messages", "channel_id", r["channel_id"])
        if not m:
            continue
        done = db.latest_log(r["channel_id"], "instagram_dm")
        out.append({"channel_id": r["channel_id"], "Influencer": r["name"],
                    "Instagram": r.get("instagram_url") or "Not found - search manually",
                    "DM Text": m["instagram_dm"],
                    "Status": "sent_manual" if done else "pending_manual"})
    return out


def messages_markdown(db) -> str:
    lines = ["# Personalised outreach messages\n"]
    for r in message_rows(db):
        lines += [f"## {r['Influencer']}  \n*{r['Email']} - angle: {r['Collab Angle']} - generated by {r['Generated By']}*\n",
                  f"**Subject:** {r['Subject']}\n", f"**Email ({r['Email Words']} words)**\n", r["Email Pitch"],
                  f"\n**Instagram DM ({r['DM Words']} words)**\n", f"> {r['Instagram DM']}\n", "---\n"]
    return "\n".join(lines)


def export_all(cfg: dict, db) -> dict:
    out = Path(cfg["paths"]["output_dir"])
    files = {
        "influencer_dataset.csv": dataset_rows(db),
        "shortlisted_enriched.csv": enriched_rows(db),
        "personalized_messages.csv": message_rows(db),
        "outreach_tracker.csv": tracker_rows(db),
        "dm_queue.csv": dm_queue_rows(db),
    }
    paths = {n: _write(out / n, rows) for n, rows in files.items()}
    (out / "personalized_messages.md").write_text(messages_markdown(db), encoding="utf-8")
    paths["personalized_messages.md"] = str(out / "personalized_messages.md")
    return paths
